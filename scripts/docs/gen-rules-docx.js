function cell(text, width, { head = false, fill, bold = false, align } = {}) {
  const lines = Array.isArray(text) ? text : [text];
  return new TableCell({
    borders,
    width: { size: width, type: WidthType.DXA },
    shading: head ? { fill: BLUE, type: ShadingType.CLEAR, color: 'auto' } : fill ? { fill, type: ShadingType.CLEAR, color: 'auto' } : undefined,
    margins: { top: 70, bottom: 70, left: 110, right: 110 },
    verticalAlign: VerticalAlign.CENTER,
    children: lines.map(
      (l) =>
        new Paragraph({
          alignment: align ?? (head ? AlignmentType.CENTER : AlignmentType.LEFT),
          spacing: { line: 300 },
          children: runs(l, head ? { bold: true, color: 'FFFFFF', size: 20 } : { size: 20, bold }),
        }),
    ),
  });
}
function table(headers, rows, widths, { firstColFill = true, center = [] } = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({ tableHeader: true, children: headers.map((h, i) => cell(h, widths[i], { head: true })) }),
      ...rows.map(
        (r, ri) =>
          new TableRow({
            cantSplit: true,
            children: r.map((c, i) =>
              cell(c, widths[i], {
                fill: i === 0 && firstColFill ? LIGHT : ri % 2 ? PALE : undefined,
                bold: i === 0 && firstColFill,
                align: center.includes(i) ? AlignmentType.CENTER : undefined,
              }),
            ),
          }),
      ),
    ],
  });
}
// 提示框（单格表格，带底色）
function box(title, lines, fill = GOLD) {
  return new Table({
    width: { size: W, type: WidthType.DXA },
    columnWidths: [W],
    rows: [
      new TableRow({
        children: [
          new TableCell({
            width: { size: W, type: WidthType.DXA },
            shading: { fill, type: ShadingType.CLEAR, color: 'auto' },
            borders: {
              top: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
              bottom: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
              right: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
              left: { style: BorderStyle.SINGLE, size: 24, color: 'C9A227' },
            },
            margins: { top: 120, bottom: 120, left: 200, right: 200 },
            children: [
              new Paragraph({ spacing: { after: 60 }, children: [new TextRun({ text: title, bold: true, color: '7A5B00' })] }),
              ...lines.map((l) => new Paragraph({ spacing: { after: 40, line: 320 }, children: runs(l, { size: 20 }) })),
            ],
          }),
        ],
      }),
    ],
  });
}
