// ---------- 小工具 ----------
function runs(text, base = {}) {
  // 支持 **加粗** 标记
  const parts = String(text).split(/(\*\*[^*]+\*\*)/).filter(Boolean);
  return parts.map((s) =>
    s.startsWith('**') ? new TextRun({ ...base, text: s.slice(2, -2), bold: true }) : new TextRun({ ...base, text: s }),
  );
}
const p = (text, opts = {}) =>
  new Paragraph({ children: runs(text, opts.run), spacing: { after: 120, line: 360 }, ...opts.para });
const h1 = (text) => new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun(text)], spacing: { before: 480 } });
